export function detectVendors(text, { params = false } = {}) {
  if (!text) return [];
  const found = new Set();
  for (const [name, re] of VENDORS) if (re.test(text)) found.add(name);
  if (params) for (const [name, re] of PARAM_HINTS) if (re.test(text)) found.add(name);
  return [...found];
}

